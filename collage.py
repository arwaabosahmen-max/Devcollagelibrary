@app.route('/')
def index():
    departments = Department.query.all()
    total_subjects = Subject.query.count()
    return render_template('index.html', departments=departments, total_subjects=total_subjects)

@app.route('/department/<int:dept_id>')
def department_detail(dept_id):
    department = Department.query.get_or_404(dept_id)
    grouped_subjects = {}
    for subject in department.subjects:
        sem = subject.semester_name
        if sem not in grouped_subjects:
            grouped_subjects[sem] = []
        grouped_subjects[sem].append(subject)
    return render_template('department.html', department=department, grouped_subjects=grouped_subjects)

