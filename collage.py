def seed_curriculum():
    if Department.query.count() == 0:
        for dept_name, semesters in curriculum_data.items():
            dept = Department(name=dept_name)
            db.session.add(dept)
            db.session.commit()
            
            for sem_name, subjects_list in semesters.items():
                for sub_name in subjects_list:
                    subject = Subject(name=sub_name, semester_name=sem_name, department_id=dept.id)
                    db.session.add(subject)
            db.session.commit()

if __name__ == '__main__':
    with app.app_context():
        db.create_all()
        seed_curriculum()
    app.run(debug=True)
